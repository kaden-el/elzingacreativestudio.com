def nearby_block(service_key, city_slug, city):
    """Same service, nearby towns — plus the sibling services in this town."""
    svc = SERVICES[service_key]
    rows = []
    for n in city["nearby"]:
        if n in CITIES:
            rows.append(f'    <li><a href="{url_for(service_key, n)}"><strong>{CITIES[n]["name"]}, MI</strong>, {svc["short"]} for {CITIES[n]["name"]} listings</a></li>')
        else:
            # Town has a photography page but is outside the matrix — link that instead.
            pretty = n.replace("-", " ").title()
            rows.append(f'    <li><a href="real-estate-photography-{n}.html"><strong>{pretty}, MI</strong>, real estate photography</a></li>')
    siblings = [k for k in SERVICE_ORDER if k != service_key]
    sib_rows = [
        f'    <li><a href="{url_for(k, city_slug)}"><strong>{SERVICES[k]["nav_label"]} in {city["name"]}</strong>, {SERVICES[k]["price_line"]}</a></li>'
        for k in siblings
    ]
    sib_rows.append(f'    <li><a href="real-estate-photography-{city_slug}.html"><strong>Real estate photography in {city["name"]}</strong>, the full HDR listing gallery</a></li>')
    return f"""<section class="nearby-areas reveal">
  <div class="nearby-inner">
    <span class="nearby-label">Everything else in {city['name']}</span>
    <h2 class="nearby-title">More listing coverage in <em>{city['name']}.</em></h2>
    <ul class="nearby-list">
{chr(10).join(sib_rows)}
    </ul>
    <span class="nearby-label" style="margin-top:32px;display:block;">Nearby towns</span>
    <h2 class="nearby-title">{svc['label']} in nearby <em>West Michigan towns.</em></h2>
    <ul class="nearby-list">
{chr(10).join(rows)}
    </ul>
  </div>
</section>"""


