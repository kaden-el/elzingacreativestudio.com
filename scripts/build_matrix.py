def load_shell():
    src = open(DONOR, encoding="utf-8").read()
    grab = lambda pat: re.search(pat, src, re.S).group(0)
    return {
        "gtm_head": grab(r"<!-- Google Tag Manager -->.*?<!-- End Google Tag Manager -->"),
        "gtm_body": grab(r"<!-- Google Tag Manager \(noscript\) -->.*?<!-- End Google Tag Manager \(noscript\) -->"),
        "fonts": grab(r'<link rel="preconnect".*?rel="stylesheet">'),
        "css": grab(r'<link rel="stylesheet" href="css/cobalt-gallery.css">\s*<link rel="stylesheet" href="css/brand.css">'),
        "style": grab(r"<style>.*?</style>"),
        "header": grab(r"<header id=\"site-header\">.*?</header>"),
        "footer_scripts": grab(r"<script>\s*const hdr = document\.getElementById.*?</body>\s*</html>"),
    }


