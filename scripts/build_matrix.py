def crosslink_block(city_slug):
    city = CITIES[city_slug]
    rows = "\n".join(
        f'    <li><a href="{url_for(k, city_slug)}"><strong>{SERVICES[k]["nav_label"]} in {city["name"]}</strong>, {SERVICES[k]["price_line"]}</a></li>'
        for k in SERVICE_ORDER
    )
    return f"""{CROSSLINK_START}
<section class="nearby-areas reveal">
  <div class="nearby-inner">
    <span class="nearby-label">More in {city['name']}</span>
    <h2 class="nearby-title">Everything else we shoot in <em>{city['name']}.</em></h2>
    <ul class="nearby-list">
{rows}
    </ul>
  </div>
</section>
{CROSSLINK_END}"""


def inject_crosslinks(dry_run=False):
    """Add (or refresh) the matrix link block on each city photography page."""
    touched = []
    for slug in CITY_ORDER:
        path = os.path.join(ROOT, f"real-estate-photography-{slug}.html")
        if not os.path.exists(path):
            print(f"  ! no photography page for {slug}, skipping crosslink")
            continue
        src = open(path, encoding="utf-8").read()
        block = crosslink_block(slug)
        if CROSSLINK_START in src:
            new = re.sub(re.escape(CROSSLINK_START) + r".*?" + re.escape(CROSSLINK_END), lambda _: block, src, flags=re.S)
        else:
            # The cta-band section carries varying attributes across pages, and a
            # couple of pages have none at all — fall back to the footer.
            m = re.search(r'<section id="cta-band"[^>]*>', src) or re.search(r"<footer[^>]*>", src)
            if not m:
                print(f"  ! no cta-band or footer anchor in {slug}, skipping crosslink")
                continue
            new = src[: m.start()] + block + "\n\n" + src[m.start():]
        if new != src:
            touched.append(slug)
            if not dry_run:
                open(path, "w", encoding="utf-8").write(new)
    return touched


# ------------------------------------------------------------------- sitemap

def update_sitemap(urls, dry_run=False):
    path = os.path.join(ROOT, "sitemap.xml")
    src = open(path, encoding="utf-8").read()
    today = date.today().isoformat()
    existing = set(re.findall(r"<loc>(.*?)</loc>", src))
    entries = []
    for u in urls:
        full = BASE + u
        if full in existing:
            continue
        entries.append(
            f"  <url>\n    <loc>{full}</loc>\n    <lastmod>{today}</lastmod>\n"
            f"    <changefreq>monthly</changefreq>\n    <priority>0.7</priority>\n  </url>"
        )
    if not entries:
        return 0
    new = src.replace("</urlset>", "\n".join(entries) + "\n</urlset>")
    if not dry_run:
        open(path, "w", encoding="utf-8").write(new)
    return len(entries)


# ----------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true", help="fail if any page is out of date")
    args = ap.parse_args()

    shell = load_shell()
    written, unchanged, stale, refused = [], [], [], []

    for city_slug in CITY_ORDER:
        for service_key in SERVICE_ORDER:
            url = url_for(service_key, city_slug)
            path = os.path.join(ROOT, url)
            out = render(shell, service_key, city_slug)
            if os.path.exists(path):
                cur = open(path, encoding="utf-8").read()
                if GENERATED not in cur:
                    refused.append(url)
                    continue
                if cur == out:
                    unchanged.append(url)
                    continue
                stale.append(url)
            if args.check:
                continue
            if not args.dry_run:
                open(path, "w", encoding="utf-8").write(out)
            written.append(url)

    all_urls = [url_for(s, c) for c in CITY_ORDER for s in SERVICE_ORDER]

    if args.check:
        print(f"check: {len(unchanged)} current, {len(stale)} stale, {len(refused)} hand-edited")
        for u in stale:
            print("  STALE:", u)
        for u in refused:
            print("  HAND-EDITED (not overwritten):", u)
        return 1 if stale else 0

    added = update_sitemap(all_urls, dry_run=args.dry_run)
    linked = inject_crosslinks(dry_run=args.dry_run)

    print(f"matrix: {len(CITY_ORDER)} cities x {len(SERVICE_ORDER)} services = {len(all_urls)} pages")
    print(f"  written/updated : {len(written)}")
    print(f"  unchanged       : {len(unchanged)}")
    print(f"  refused (hand-edited): {len(refused)}")
    print(f"  sitemap entries added : {added}")
    print(f"  city pages cross-linked: {len(linked)}")
    if args.dry_run:
        print("  (dry run — nothing written)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
