def url_for(service_key, city_slug):
    return f"{SERVICES[service_key]['slug']}-{city_slug}.html"


def esc(s):
    """Escape for a JSON-LD string literal."""
    return json.dumps(s)[1:-1]


def bullets(items):
    return "\n".join(f"    <li>{i}</li>" for i in items)


