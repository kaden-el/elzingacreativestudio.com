"""
ECS programmatic local-SEO matrix builder.

Renders {service} x {city} pages from scripts/matrix_data.py, keeps sitemap.xml
in sync, and injects the crawl path (a "More in {City}" block) into the existing
real-estate-photography-{city}.html pages.

    python3 scripts/build_matrix.py            # build everything
    python3 scripts/build_matrix.py --dry-run  # report, write nothing
    python3 scripts/build_matrix.py --check    # verify built pages match data (CI-ish)

Design notes
------------
* The visual shell (inline <style>, header, footer, motion scripts) is lifted
  verbatim from an existing city page, so matrix pages inherit Edition 03 brand
  styling with no separate CSS to drift.
* Every generated file carries a GENERATED marker. The builder refuses to
  overwrite a file that does not carry it, so a hand-edited page is never
  silently clobbered.
* Idempotent: running twice produces byte-identical output.
"""

